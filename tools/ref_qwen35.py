def _iq2_grid(grid_hex, shape):
    """Generic IQ2-family grid builder: gguf-py's init_grid, 2 bits/elem.

    grid_hex is the ASCII hex blob; the bytes pack four 2-bit indices
    (shifts 0, 2, 4, 6, low first) into the (8, 25, 43) magnitude map.
    """
    # grid_hex is adjacent b"..." literals with no commas, which Python
    # implicitly concatenates into ONE bytes object (the file's blob
    # pattern, same as _IQ1S_GRID_HEX); frombuffer reads the ASCII hex
    # chars as uint8 directly. No join: join would iterate the bytes'
    # ints (measured TypeError).
    raw = np.frombuffer(grid_hex, dtype=np.uint8).reshape(-1, 2)
    nib = (np.where(raw > 0x40, raw + 9, raw) & 0x0F).astype(np.uint8)
    byt = ((nib[:, 0] << 4) | nib[:, 1]).astype(np.uint8)
    elems = ((byt.reshape(-1, 1) >>
              np.array([0, 2, 4, 6], dtype=np.uint8)) & 3).reshape(-1)
    code = np.array((0x08, 0x19, 0x2B), dtype=np.float32)
    # gguf-py's init_grid leaves the codebook as (1, 1, N, M) so that the
    # decode branches can take_along_axis on axis=-2; match that shape here.
    return np.take_along_axis(
        code.reshape(1, -1), elems.reshape(-1, 1), axis=-1).reshape(
        (1, 1) + tuple(shape))


