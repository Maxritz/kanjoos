def _iq3s_grid():
    """The (512, 4) float32 codebook for IQ3_S."""
    global _IQ3S_GRID
    if _IQ3S_GRID is None:
        raw = np.frombuffer(_IQ3S_GRID_HEX, dtype=np.uint8).reshape(-1, 2)
        nib = (np.where(raw > 0x40, raw + 9, raw) & 0x0F).astype(np.uint8)
        byt = ((nib[:, 0] << 4) | nib[:, 1]).astype(np.uint8)
        # 3 bits per element, two per byte at shifts 0 and 4 (mask 0x7).
        elems = ((byt.reshape(-1, 1) >>
                  np.array([0, 4], dtype=np.uint8)) & 7).reshape(-1)
        code = np.array((1, 3, 5, 7, 9, 11, 13, 15), dtype=np.float32)
        _IQ3S_GRID = np.take_along_axis(
            code.reshape(1, -1), elems.reshape(-1, 1), axis=-1).reshape(512, 4)
    return _IQ3S_GRID


