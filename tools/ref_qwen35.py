_IQ1S_GRID = None


def _iq1s_grid():
    """The (2048, 8) float32 codebook shared by IQ1_S and IQ1_M."""
    global _IQ1S_GRID
    if _IQ1S_GRID is None:
        raw = np.frombuffer(_IQ1S_GRID_HEX, dtype=np.uint8).reshape(-1, 2)
        # Hex chars to nibbles ('a'-'f' sit above 0x40 and need +9 before the
        # mask); then four 2-bit elements per byte, low bits first. The same
        # steps as gguf-py's init_grid with bits_per_elem=2.
        nib = (np.where(raw > 0x40, raw + 9, raw) & 0x0F).astype(np.uint8)
        packed = (nib[:, 0] << 4) | nib[:, 1]
        elems = ((packed.reshape(-1, 1) >>
                  np.array([0, 2, 4, 6], dtype=np.uint8)) & 3).reshape(-1, 1)
        code = np.array((-1, 0, 1), dtype=np.float32).reshape(1, -1)
        _IQ1S_GRID = np.take_along_axis(code, elems, axis=-1).reshape(2048, 8)
    return _IQ1S_GRID


